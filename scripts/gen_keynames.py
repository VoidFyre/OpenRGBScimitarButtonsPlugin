#!/usr/bin/env python3
"""Generate src/KeyNames.cpp from linux/input-event-codes.h.

Usage: scripts/gen_keynames.py [/usr/include/linux/input-event-codes.h] > src/KeyNames.cpp
"""
import re
import sys

header = sys.argv[1] if len(sys.argv) > 1 else "/usr/include/linux/input-event-codes.h"

# Keys a keyboard can actually type; uinput advertises all of them.
MAX_CODE = 248  # KEY_MICMUTE

PRETTY = {
    "ESC": "Esc", "BACKSPACE": "Backspace", "TAB": "Tab", "ENTER": "Enter", "SPACE": "Space",
    "MINUS": "-", "EQUAL": "=", "LEFTBRACE": "[", "RIGHTBRACE": "]", "SEMICOLON": ";",
    "APOSTROPHE": "'", "GRAVE": "`", "BACKSLASH": "\\\\", "COMMA": ",", "DOT": ".", "SLASH": "/",
    "LEFTCTRL": "Ctrl", "RIGHTCTRL": "Right Ctrl", "LEFTSHIFT": "Shift", "RIGHTSHIFT": "Right Shift",
    "LEFTALT": "Alt", "RIGHTALT": "AltGr", "LEFTMETA": "Super", "RIGHTMETA": "Right Super",
    "CAPSLOCK": "Caps Lock", "NUMLOCK": "Num Lock", "SCROLLLOCK": "Scroll Lock", "SYSRQ": "Print Screen",
    "PAGEUP": "Page Up", "PAGEDOWN": "Page Down", "HOME": "Home", "END": "End",
    "INSERT": "Insert", "DELETE": "Delete", "UP": "Up", "DOWN": "Down", "LEFT": "Left", "RIGHT": "Right",
    "KPASTERISK": "Num *", "KPMINUS": "Num -", "KPPLUS": "Num +", "KPDOT": "Num .", "KPENTER": "Num Enter",
    "KPSLASH": "Num /", "KPEQUAL": "Num =", "KPCOMMA": "Num ,", "KPPLUSMINUS": "Num +/-",
    "MUTE": "Mute", "VOLUMEDOWN": "Volume Down", "VOLUMEUP": "Volume Up",
    "PLAYPAUSE": "Play/Pause", "NEXTSONG": "Next Track", "PREVIOUSSONG": "Previous Track",
    "STOPCD": "Stop", "COMPOSE": "Menu", "102ND": "< >",
}

names = {}
with open(header) as f:
    for m in re.finditer(r"#define\s+KEY_(\w+)\s+(\d+|0x[0-9a-fA-F]+)\b", f.read()):
        code = int(m.group(2), 0)
        # First definition wins; later ones are aliases.
        if 0 < code <= MAX_CODE and code not in names:
            names[code] = m.group(1)

def pretty(name):
    if name in PRETTY:
        return PRETTY[name]
    if m := re.fullmatch(r"KP(\d)", name):
        return "Num " + m.group(1)
    if re.fullmatch(r"F\d+|[A-Z0-9]", name):
        return name
    return name.replace("_", " ").title()

print("""/*---------------------------------------------------------*\\
| KeyNames.cpp                                              |
|                                                           |
|   Generated by scripts/gen_keynames.py, do not edit       |
|                                                           |
|   SPDX-License-Identifier: GPL-2.0-or-later               |
\\*---------------------------------------------------------*/

#include "KeyNames.h"

const KeyName key_names[] =
{""")
for code in sorted(names):
    print(f'    {{ {code:3d}, "{pretty(names[code])}" }},')
print("""};

const unsigned int key_names_count = sizeof(key_names) / sizeof(key_names[0]);""")
